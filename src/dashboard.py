@st.cache_data
def load_analytics_data(summary_path, parquet_path):
    """Loads precomputed JSON analytics and the Parquet document dataset for one corpus."""
    summary_data = {}
    if os.path.exists(summary_path):
        with open(summary_path, "r", encoding="utf-8") as f:
            summary_data = json.load(f)

    df_articles = pd.DataFrame()
    if os.path.exists(parquet_path):
        try:
            df_articles = pd.read_parquet(parquet_path)
        except Exception:
            pass

    return summary_data, df_articles


